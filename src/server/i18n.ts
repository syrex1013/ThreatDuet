/** Translates server text into the user's language; English text is the key, {name} marks a placeholder. */
export function tr(en: string, vars?: Record<string, string | number>): string {
  // db is unset until the store opens (and in unit tests): English then.
  const text = (db?.data?.settings?.language === 'pl' && PL[en]) || en;
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}
